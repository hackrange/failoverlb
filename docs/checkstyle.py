"""
Check the built manual against the house style.

Run after every build.  These are the rules that are easy to state and easy to
break while writing, so they are worth checking mechanically rather than by
reading 100 pages again.
"""
import re
import sys
from docx import Document

d = Document("/docs/NGINX-Management-User-Guide.docx")
texts = [p.text for p in d.paragraphs]
for t in d.tables:
    texts += [c.text for r in t.rows for c in r.cells]
body = "\n".join(texts)

problems = []

dashes = body.count("—") + body.count("–")
if dashes:
    problems.append(f"{dashes} em or en dashes")

singles = re.findall(r"[a-z]\.\s(?=[A-Z])", body)
doubles = re.findall(r"[a-z]\.\s\s(?=[A-Z])", body)
bad = len(singles) - len(doubles)
if bad > 0:
    problems.append(f"{bad} sentence gaps with one space instead of two")

# Narrow on purpose.  The bare word "generated" is ordinary English here, as
# in "the generated config files", and flagging it trains people to ignore the
# check.  What matters is a claim about who or what wrote something.
ai = re.findall(
    r"\b(AI|assistant|assistants|Claude|language model|chatbot"
    r"|machine[- ]generated|auto[- ]generated|generated by)\b",
    body, re.I)
if ai:
    problems.append(f"{len(ai)} references to AI or assistants: {set(ai)}")

# Whatever the person building this said must not appear.  Configured rather
# than listed here, because the real hostnames belong to whoever is building
# the book and not to this repository.
from docsconf import forbidden
leaked = []
for pattern in forbidden():
    leaked += re.findall(pattern, body, re.I)
if leaked:
    problems.append(f"{len(leaked)} real lab names left in: {set(leaked)}")

heads = [p.text for p in d.paragraphs if p.style.name == "Heading 1"]
numbered = [h for h in heads if re.match(r"^\d+\.", h)]
expected = list(range(1, len(numbered) + 1))
actual = [int(h.split(".")[0]) for h in numbered]
if actual != expected:
    problems.append(f"chapter numbers are {actual}, expected {expected}")

words = len(body.split())
print(f"  chapters {len(numbered)}   words {words:,}   "
      f"images {len(d.inline_shapes)}   tables {len(d.tables)}")
print(f"  estimated pages: {round(words/430 + len(d.inline_shapes)*0.55 + len(d.tables)*0.32 + len(numbered)*0.5)}")

if problems:
    print("\n  STYLE PROBLEMS")
    for p in problems:
        print("   ", p)
    sys.exit(1)
print("  house style: clean")
