def _stream_has_variable(key: str) -> bool:
    """Is every variable in this hash key one a stream actually has."""
    used = re.findall(r"\$[A-Za-z0-9_]+", str(key))
    return bool(used) and all(v in _STREAM_VARIABLES for v in used)


def _safe_name(name: str) -> str:
    """
    Make a user-supplied name safe as a filename and an nginx identifier.
    """
    cleaned = re.sub(r"[^A-Za-z0-9._-]", "_", str(name))
    return cleaned[:64] or "unnamed"


def _safe_var(name: str) -> str:
    """Same idea, for an nginx variable name (word characters only)."""
    cleaned = re.sub(r"[^A-Za-z0-9_]", "_", str(name))
    return cleaned[:48] or "unnamed"


# Public aliases, used by the API to check for name collisions.  It must use
# these exact functions, since a drifting copy would let one object silently
# overwrite another.
safe_name = _safe_name
safe_var = _safe_var


def _safe_header(name: str) -> str:
    """
    Make an HTTP header name safe to write into a directive.  We strip
    rather than quote, since nginx won't accept a quoted header name.
    """
    cleaned = re.sub(r"[^A-Za-z0-9-]", "", str(name))
    return cleaned[:64] or "X-Fleet-Token"


def _version_at_least(version: str, target: tuple) -> bool:
    """Is this nginx version at least the given one."""
    if not version:
        # Assume new; the installer pins a recent version.
        return True
    try:
        parts = tuple(int(p) for p in version.split(".")[:3])
    except (ValueError, AttributeError):
        return True
    return parts >= target
