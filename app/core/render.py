def waf_path_to_regex(path: str) -> str:
    """
    Turn a glob-style path into a regular expression.

    Learning produces one exclusion per path, which on a git server means one
    row per repository.  Storing a glob keeps it readable and editable, and
    covers repositories created later.  The regex is only built here.

      *   anything except a slash, so one path segment
      **  anything at all, slashes included

    Everything outside a star is escaped, so the dot in `.git` stays literal.
    Not anchored at the end: these replace `@beginsWith`, so an exclusion
    covers everything under its path.
    """
    out = []
    i = 0
    while i < len(path):
        if path.startswith("**", i):
            out.append(".*")
            i += 2
        elif path[i] == "*":
            out.append("[^/]*")
            i += 1
        else:
            j = i
            while j < len(path) and path[j] != "*":
                j += 1
            out.append(re.escape(path[i:j]))
            i = j
    return "^" + "".join(out)


def _waf_path_match(path: str) -> str:
    """
    The ModSecurity operator for one exclusion's path.  Plain paths use the
    cheaper `@beginsWith`; only paths with a star pay for `@rx`.
    """
    if "*" in path:
        return "@rx " + waf_path_to_regex(path)
    return "@beginsWith " + path
