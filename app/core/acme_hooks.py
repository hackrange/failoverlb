"""
The certbot hook scripts.

certbot runs on the host, outside the container, so it can only reach us by
running a shell script.  These scripts pass the challenge token to the
manager, which copies it to every node before Let's Encrypt checks.

Let's Encrypt validates against whatever address DNS returns.  With round
robin DNS, a moved address or a stale resolver, that may not be the node
running certbot, so every node needs the token.

The scripts are kept tiny: a shared secret and one endpoint call.  Logic
belongs on the Python side where it can be tested.
"""

import logging
import secrets

from app.config import get_settings
from app.core import settings_store
from app.core.agent_client import AgentError, get_agent

log = logging.getLogger("nfm.acme.hooks")

HOOK_DIR = "/usr/local/lib/nginx-fleet-manager"
AUTH_HOOK = f"{HOOK_DIR}/acme-auth-hook.sh"
CLEANUP_HOOK = f"{HOOK_DIR}/acme-cleanup-hook.sh"

HOOK_SECRET_KEY = "acme_hook_secret"


def get_hook_secret() -> str:
    """
    The shared secret the hooks use to authenticate.

    Created once and persisted, so a restart in the middle of an issue doesn't
    leave the hooks unable to authenticate.
    """
    existing = settings_store.get(HOOK_SECRET_KEY)
    if existing:
        return existing

    secret = secrets.token_urlsafe(32)
    settings_store.set(HOOK_SECRET_KEY, secret, actor="system")
    log.info("made a new secret for the certbot hooks")
    return secret


def _script(action: str, secret: str, port: int, root_path: str) -> str:
    """
    Build one hook script.  It reads the token from the environment (where
    certbot puts it) and posts it to the manager on localhost.

    --insecure is intentional: the GUI certificate is self signed and the
    connection never leaves loopback.  The secret header is the auth.
    """
    return f"""#!/usr/bin/env bash
# Generated by Failover LB.  Do not edit.
#
# certbot runs this while proving we own a domain.  It takes the challenge
# token and hands it to the manager, which copies it to every node in the
# cluster before validation starts.  That way it does not matter which node
# Lets Encrypt actually connects to.
set -euo pipefail

MANAGER="https://127.0.0.1:{port}{root_path}/api/acme/hook"

# certbot puts these in the environment for us.
TOKEN="${{CERTBOT_TOKEN:-}}"
VALIDATION="${{CERTBOT_VALIDATION:-}}"

if [ -z "$TOKEN" ]; then
    echo "no CERTBOT_TOKEN in the environment, nothing to do" >&2
    exit 1
fi

response=$(curl --silent --show-error --insecure --max-time 30 \\
    --header "Content-Type: application/json" \\
    --header "X-NFM-Hook-Secret: {secret}" \\
    --data "{{\\"action\\":\\"{action}\\",\\"token\\":\\"$TOKEN\\",\\"value\\":\\"$VALIDATION\\"}}" \\
    "$MANAGER" 2>&1) || {{
        echo "could not reach the manager at $MANAGER" >&2
        echo "$response" >&2
        exit 1
    }}

echo "$response"

# A moment for the token to land on the other nodes before certbot tells Lets
# Encrypt to go and look.  The manager writes them all before answering, so
# this is only covering the gap between a file being written and nginx being
# able to serve it.
{'sleep 2' if action == 'publish' else 'true'}
"""


async def ensure_hooks() -> dict:
    """
    Write the hook scripts onto the host.

    Called at startup and again before any http-01 issue, since a rebuilt node
    won't have them and certbot's error doesn't explain why.
    """
    settings = get_settings()
    secret = get_hook_secret()
    root_path = settings.root_path.rstrip("/")

    scripts = {
        "acme-auth-hook.sh": _script("publish", secret, settings.gui_port, root_path),
        "acme-cleanup-hook.sh": _script("cleanup", secret, settings.gui_port, root_path),
    }

    try:
        result = await get_agent().write_hook_scripts(scripts=scripts)
        log.info("certbot hook scripts are in place")
        return {"ok": True, "written": result.get("written", [])}
    except AgentError as exc:
        log.error("could not write the certbot hooks: %s", exc)
        return {"ok": False, "error": str(exc)}


async def hooks_present() -> bool:
    """Is the auth hook actually on disk."""
    try:
        await get_agent().read_file(AUTH_HOOK)
        return True
    except AgentError:
        return False
